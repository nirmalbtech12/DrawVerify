using System.Text;
using DrawVerify.Application.DxfUpload;
using DrawVerify.Application.Services;
using DrawVerify.Geometry.Models;
using Xunit;

namespace DrawVerify.Application.Tests;

public sealed class Kan125DxfGenerationServiceTests
{
    [Fact(DisplayName = "TD-04 writes supported entities with deterministic invariant output")]
    public void Writer_serializes_supported_entities_with_invariant_formatting()
    {
        var drawing = new ProjectionDrawing(
            ProjectionDrawingView.Front,
            new ProjectionDrawingEntity[]
            {
                new(ProjectionDrawingEntityType.Line, new[] { 0d, 0d, 1.25d, 2.5d }),
                new(ProjectionDrawingEntityType.Arc, new[] { 2d, 3d, 4d, 0d, Math.PI / 2 }),
                new(ProjectionDrawingEntityType.Circle, new[] { 5d, 6d, 7d }),
                new(ProjectionDrawingEntityType.Polyline, new[] { 8d, 9d, 10d, 11d })
            },
            new[] { new ProjectionDrawingDimension("Linear", 12.5d, 1d, 2d) },
            0.001d,
            Array.Empty<string>());

        var first = Encoding.ASCII.GetString(DxfFileWriter.Write(new[] { drawing }));
        var second = Encoding.ASCII.GetString(DxfFileWriter.Write(new[] { drawing }));

        Assert.Equal(first, second);
        Assert.Contains("0\nLINE\n", first);
        Assert.Contains("0\nARC\n", first);
        Assert.Contains("0\nCIRCLE\n", first);
        Assert.Contains("0\nLWPOLYLINE\n", first);
        Assert.Contains("1.25", first);
        Assert.Contains("2.5", first);
        Assert.Contains("0\nSECTION\n", first);
        Assert.EndsWith("0\nEOF\n", first);
        Assert.Equal(1, drawing.DimensionCount);
    }

    [Fact(DisplayName = "TD-05 reports bounded progress and terminal failures")]
    public void Generation_service_has_progress_cancellation_and_failure_cleanup()
    {
        var source = Read("src", "DrawVerify.Application", "Services", "DxfDrawingGenerationService.cs");
        Assert.Contains("IProgress<DxfDrawingGenerationProgress>", source);
        Assert.Contains("OperationCanceledException", source);
        Assert.Contains("finally", source);
        Assert.Contains("File.Delete", source);
        Assert.Contains("2D drawing generation failed", source);
        Assert.Contains("CentralizedLogger", Read("src", "DrawVerify.Application", "Services", "DxfDrawingGenerationService.cs"));
    }

    [Fact(DisplayName = "TD-04 validates generated bytes before persistence")]
    public async Task Generated_payload_passes_structural_validator()
    {
        const string payload = "0\nSECTION\n2\nENTITIES\n0\nLINE\n10\n0\n20\n0\n11\n1\n21\n1\n0\nENDSEC\n0\nEOF\n";
        await using var stream = new MemoryStream(Encoding.ASCII.GetBytes(payload));
        var result = await DxfFileValidator.ValidateAsync(stream, stream.Length, 1);
        Assert.True(result.IsValid);
    }

    private static string Read(params string[] parts)
    {
        var directory = new DirectoryInfo(AppContext.BaseDirectory);
        while (directory is not null)
        {
            var path = Path.Combine(new[] { directory.FullName }.Concat(parts).ToArray());
            if (File.Exists(path)) return File.ReadAllText(path);
            directory = directory.Parent;
        }
        throw new FileNotFoundException(string.Join(Path.DirectorySeparatorChar, parts));
    }

}
